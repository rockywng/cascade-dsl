"""Lower a checked pipeline to deployable artifacts:

  pipeline.sql    Flink SQL script (SET, CREATE TEMPORARY TABLE/VIEW, EXECUTE STATEMENT SET)
  manifest.json   platform metadata: graph, schemas, changelog modes, state identities,
                  secrets to inject, connector artifacts. The upgrade checker diffs manifests.
"""
from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass, field

from . import __version__
from .analyze import Checked, aligned_parallelisms
from .connectors import CATALOG, SECRET_RE, spec_for
from .ir import OutputColumn, Pipeline
from .util import h, normalize_sql

ASSERT_FN = "CASCADE_ASSERT"
ASSERT_CLASS = "dev.cascade.runtime.AssertFunction"
EXPECT_FN = "CASCADE_EXPECT"
EXPECT_CLASS = "dev.cascade.runtime.ExpectFunction"
SOURCE_IDENTITY_KEYS = {"connector", "topic", "table-name", "schema-name", "database-name", "hostname",
                        "catalog-database", "catalog-table", "path", "slot.name", "properties.group.id"}


def q(name: str) -> str:
    return "`" + name.replace("`", "``") + "`"


def lit(value) -> str:
    return "'" + str(value).replace("'", "''") + "'"


def interval(ms: int) -> str:
    if ms % 1000 == 0:
        return f"INTERVAL '{ms // 1000}' SECOND"
    return f"INTERVAL '{ms / 1000:.3f}' SECOND"


def with_clause(opts: dict) -> str:
    return "WITH (\n" + ",\n".join(f"  {lit(k)} = {lit(v)}" for k, v in opts.items()) + "\n)"


@dataclass
class Stmt:
    """One generated statement. Tools (verify, test runner, restore test) rewrite these by kind
    instead of pattern-matching SQL text."""

    kind: str  # set | function | source | view | quarantine | sink | insert
    name: str
    sql: str = ""
    comment: str | None = None
    columns: list[tuple[str, str]] = field(default_factory=list)  # tables
    extra: list[str] = field(default_factory=list)  # tables: computed cols, watermark, PK
    options: dict = field(default_factory=dict)  # tables: WITH options
    query: str = ""  # insert: the SELECT feeding the target
    on_conflict: str | None = None  # insert

    def render(self) -> str:
        if self.kind in ("source", "sink", "quarantine"):
            body = [f"  {q(n)} {t}" for n, t in self.columns] + [f"  {x}" for x in self.extra]
            return f"CREATE TEMPORARY TABLE {q(self.name)} (\n" + ",\n".join(body) + "\n) " \
                + with_clause(self.options) + ";"
        if self.kind == "insert":
            conflict = f"\nON CONFLICT DO {self.on_conflict.upper()}" if self.on_conflict else ""
            return f"INSERT INTO {q(self.name)}\n{self.query}{conflict};"
        return self.sql

    def with_options(self, options: dict) -> "Stmt":
        return Stmt(self.kind, self.name, self.sql, self.comment, self.columns, self.extra, options,
                    self.query, self.on_conflict)


def render_script(stmts: list[Stmt], header: list[str] | None = None, statement_set: str = "EXECUTE") -> str:
    out = list(header or [])
    prev = None
    for st in stmts:
        if st.kind == "insert":
            continue
        if st.kind != "set" and not (prev == st.kind == "view" and st.comment is None) \
                and not (prev == "set" and st.kind == "set"):
            out.append("")
        if st.comment:
            out.append(f"-- {st.comment}")
        out.append(st.render())
        prev = st.kind
    inserts = [st.render() for st in stmts if st.kind == "insert"]
    if inserts:
        out.append("")
        out.append(f"{statement_set} STATEMENT SET\nBEGIN\n\n" + "\n\n".join(inserts) + "\n\nEND;")
    return "\n".join(out) + "\n"


class Lowered:
    def __init__(self, statements: list[Stmt], header: list[str], manifest: dict | None):
        self.statements = statements
        self.header = header
        self.sql = render_script(statements, header)
        self.manifest = manifest


def lower(c: Checked, partial: bool = False) -> Lowered:
    """Lower to statements. `partial` skips everything that needs fully inferred schemas
    (sinks, quarantine tables, manifest) and is used for exact schema inference."""
    p = c.pipeline
    stmts: list[Stmt] = []
    header = [f"-- Generated by cascade {__version__} from {p.file}"
              + (f" (env: {p.env})" if p.env else "") + ". Do not edit.",
              f"-- pipeline: {p.name}" + (f" | owner: {p.owner}" if p.owner else "")]
    settings = {"pipeline.name": p.name}
    if p.state_ttl_ms is not None:
        settings["table.exec.state.ttl"] = f"{p.state_ttl_ms} ms"
    if p.scaling and p.scaling.max_parallelism:
        settings["pipeline.max-parallelism"] = str(p.scaling.max_parallelism)
    if p.scaling and p.scaling.parallelism:
        settings["parallelism.default"] = str(p.scaling.parallelism)
    settings.update(c.settings)
    settings.update(p.flink_config)
    for k, v in settings.items():
        stmts.append(Stmt("set", k, f"SET {lit(k)} = {lit(v)};", options={k: v}))

    actions = {e.on_violation for m in p.models.values() for e in m.expectations}
    if "fail" in actions:
        stmts.append(Stmt("function", ASSERT_FN, f"CREATE TEMPORARY SYSTEM FUNCTION IF NOT EXISTS {ASSERT_FN} "
                                                 f"AS {lit(ASSERT_CLASS)} LANGUAGE JAVA;"))
    if actions & {"drop", "quarantine"}:
        stmts.append(Stmt("function", EXPECT_FN, f"CREATE TEMPORARY SYSTEM FUNCTION IF NOT EXISTS {EXPECT_FN} "
                                                 f"AS {lit(EXPECT_CLASS)} LANGUAGE JAVA;"))

    _lower_functions(p, stmts)

    for s in p.sources.values():
        extra = []
        if s.processing_time:
            extra.append(f"{q(s.processing_time)} AS PROCTIME()")
        if s.event_time:
            et = q(s.event_time.column)
            expr = s.event_time.expression
            if expr == "source":
                extra.append(f"WATERMARK FOR {et} AS SOURCE_WATERMARK()")
            elif expr:
                extra.append(f"WATERMARK FOR {et} AS {expr}")
            else:
                extra.append(f"WATERMARK FOR {et} AS {et} - {interval(s.event_time.max_out_of_orderness_ms)}"
                             if s.event_time.max_out_of_orderness_ms else f"WATERMARK FOR {et} AS {et}")
        if s.primary_key:
            extra.append(f"PRIMARY KEY ({', '.join(map(q, s.primary_key))}) NOT ENFORCED")
        stmts.append(Stmt("source", s.name, comment=f"source: {s.name}" + (f" -- {s.description}" if s.description else ""),
                          columns=[(col.name, col.type.text) for col in s.columns], extra=extra,
                          options=c.options.get(s.name, {})))

    for name in c.order:
        _lower_model(c, name, stmts, partial)

    if not partial:
        for k in p.sinks.values():
            rel = p.relations[k.from_]
            cols = [(col.name, col.type.with_nullable(True).text if col.name not in k.primary_key
                     else col.type.with_nullable(False).text) for col in rel.columns]
            extra = [f"PRIMARY KEY ({', '.join(map(q, k.primary_key))}) NOT ENFORCED"] if k.primary_key else []
            stmts.append(Stmt("sink", k.name, comment=f"sink: {k.name} <- {k.from_} ({k.mode})",
                              columns=cols, extra=extra, options=c.options[k.name]))
            select = ", ".join(q(col.name) for col in rel.columns)
            stmts.append(Stmt("insert", k.name, query=f"SELECT {select}\nFROM {q(k.from_)}",
                              on_conflict=k.on_conflict))

    lowered = Lowered(stmts, header, None)
    if not partial:
        lowered.manifest = _manifest(c, lowered.sql)
    return lowered


def _lower_functions(p: Pipeline, stmts: list[Stmt]):
    import os
    from .udfs import SHIM_MODULE, python_dir, python_functions
    if python_functions(p):
        d = python_dir(p)
        stmts.append(Stmt("set", "python.files", f"SET 'python.files' = {lit(d)};", options={"python.files": d}))
    for f in p.functions.values():
        head = f"CREATE TEMPORARY SYSTEM FUNCTION IF NOT EXISTS {q(f.name)} AS "
        if f.language == "java":
            using = ""
            opts = {}
            if f.jar:
                jar = os.path.normpath(os.path.join(p.root_dir, f.jar))
                using = f" USING JAR {lit(jar)}"
                opts = {"jar": jar}
            stmts.append(Stmt("function", f.name, f"{head}{lit(f.class_name)} LANGUAGE JAVA{using};",
                              comment=f"function: {f.name}" + (f" -- {f.description}" if f.description else ""),
                              options=opts))
        else:
            stmts.append(Stmt("function", f.name, f"{head}{lit(SHIM_MODULE + '.' + f.name)} LANGUAGE PYTHON;",
                              comment=f"function: {f.name} ({f.file}:{f.function})", options={"python": True}))


def _lower_model(c: Checked, name: str, stmts: list[Stmt], partial: bool):
    p = c.pipeline
    m = p.models[name]
    rel = p.relations[name]
    comment = f"model: {name}" + (f" -- {m.description}" if m.description else "")
    body = m.sql.strip().rstrip(";").rstrip()

    def view(vname, sql, cmt=None):
        stmts.append(Stmt("view", vname, f"CREATE TEMPORARY VIEW {q(vname)} AS\n{sql};", comment=cmt))

    # contract casts for columns whose inferred type is unknown or differs
    casts = None
    if m.columns is not None:
        inferred = c.inferred.get(name)
        need = []
        for i, col in enumerate(m.columns):
            got = inferred[i].type if inferred and i < len(inferred) else None
            if got is None or not got.same_base(col.type):
                need.append(col.name)
        if need:
            casts = [f"CAST({q(col.name)} AS {col.type.with_nullable(True).text}) AS {q(col.name)}"
                     if col.name in need else q(col.name) for col in m.columns]

    if not m.expectations and casts is None:
        view(name, body, comment)
        return

    base = f"{name}__raw"
    view(base, body, comment)
    if casts is not None:
        view(f"{name}__typed", f"SELECT {', '.join(casts)}\nFROM {q(base)}")
        base = f"{name}__typed"

    conds = []
    for e in m.expectations:
        if e.on_violation == "fail":
            conds.append(f"{ASSERT_FN}(({e.check}) IS TRUE, {lit(name)}, {lit(e.name)}, {lit(e.check)})")
    for e in m.expectations:
        if e.on_violation in ("drop", "quarantine"):
            conds.append(f"{EXPECT_FN}(({e.check}) IS TRUE, {lit(name)}, {lit(e.name)}, {lit(e.on_violation)})")
    where = "\n  AND ".join(conds)
    view(name, f"SELECT *\nFROM {q(base)}\nWHERE {where}")

    quarantined = [e for e in m.expectations if e.on_violation == "quarantine"]
    if quarantined:
        qview = f"{name}__quarantined"
        selects = [f"SELECT *, {lit(e.name)} AS `_violated_expectation`, CURRENT_TIMESTAMP AS `_quarantined_at`\n"
                   f"FROM {q(base)}\nWHERE NOT (({e.check}) IS TRUE)" for e in quarantined]
        view(qview, "\nUNION ALL\n".join(selects))
        if not partial:
            qname = f"{name}__quarantine"
            cols = [(col.name, col.type.with_nullable(True).text) for col in rel.columns]
            cols += [("_violated_expectation", "STRING"), ("_quarantined_at", "TIMESTAMP_LTZ(3)")]
            stmts.append(Stmt("quarantine", qname, columns=cols, options=c.options[qname]))
            stmts.append(Stmt("insert", qname, query=f"SELECT *\nFROM {q(qview)}"))


# --- manifest ----------------------------------------------------------------------------

def _cols(columns: list[OutputColumn] | None):
    return [{"name": col.name, "type": col.type.text if col.type else None} for col in columns or []]


def _manifest(c: Checked, sql: str) -> dict:
    p: Pipeline = c.pipeline
    nodes: dict[str, dict] = {}
    upstream: dict[str, str] = {}

    def logic_of(n):
        if n in p.sources:
            s = p.sources[n]
            ident = {k: v for k, v in c.options[n].items() if k in SOURCE_IDENTITY_KEYS}
            parts = ["source", ident, s.event_time.column if s.event_time else None,
                     s.event_time.max_out_of_orderness_ms if s.event_time else None]
            if s.event_time and s.event_time.expression:  # only when set: existing hashes stay stable
                parts.append(s.event_time.expression)
            return h(*parts)
        m = p.models[n]
        # name-free: inputs are referred to by position (their schemas are part of the state_id), so
        # renaming a model or one of its inputs keeps every state_id: views are inlined, the plan
        # doesn't change
        return h("model", normalize_sql(_unnamed_sql(c, n)),
                 [(e.check, e.on_violation) for e in m.expectations], _cols(p.relations[n].columns))

    def upstream_of(n):
        if n not in upstream:
            rel = p.relations[n]
            upstream[n] = h(logic_of(n), sorted(upstream_of(i) for i in rel.inputs))
        return upstream[n]

    for n in list(p.sources) + c.order:
        rel = p.relations[n]
        is_source = n in p.sources
        logic = logic_of(n)
        schema = h(_cols(rel.columns))
        stateful = is_source or bool(rel.stateful_ops)
        input_schemas = [h(_cols(p.relations[i].columns)) for i in rel.inputs]
        node = {
            "kind": "source" if is_source else "model",
            "backfill_copy_of": (p.sources.get(n) or p.models.get(n)).copy_of,
            "inputs": rel.inputs,
            "changelog": rel.changelog,
            "columns": _cols(rel.columns),
            "time_attributes": sorted(rel.rowtime),
            "stateful_ops": [{"kind": o.kind, "bounded": o.bounded, "detail": o.detail} for o in rel.stateful_ops],
            "logic_hash": logic,
            "schema_hash": schema,
            "upstream_hash": upstream_of(n),
            # identity of the state this node owns in a savepoint; a change => state cannot be restored
            "state_id": h(logic, input_schemas) if stateful else None,
        }
        if is_source:
            s = p.sources[n]
            spec = spec_for(p.connections[s.connection].type, p.connections[s.connection]) \
                if s.connection in p.connections else CATALOG.get(s.connection)
            node["connector"] = spec.type if spec else None
            node["options"] = c.options[n]
        nodes[n] = node

    sinks = {}
    for k in p.sinks.values():
        rel = p.relations[k.from_]
        sinks[k.name] = {
            "from": k.from_, "mode": k.mode, "primary_key": k.primary_key, "on_conflict": k.on_conflict,
            "columns": _cols(rel.columns), "schema_hash": h(_cols(rel.columns)),
            "options": c.options[k.name],
        }

    for m in p.models.values():  # quarantine destinations are sinks too: renaming a model moves them
        qname = f"{m.name}__quarantine"
        if qname in c.options:
            cols = _cols(p.relations[m.name].columns) + [{"name": "_violated_expectation", "type": "STRING"},
                                                        {"name": "_quarantined_at", "type": "TIMESTAMP_LTZ(3)"}]
            sinks[qname] = {"from": m.name, "mode": "append", "primary_key": [], "on_conflict": None,
                            "columns": cols, "schema_hash": h(cols), "options": c.options[qname],
                            "quarantine": True}

    artifacts = set()
    for conn in p.connections.values():
        spec = spec_for(conn.type, conn)
        if spec and spec.artifact:
            artifacts.add(spec.artifact)
        if spec and spec.extra_artifacts:
            artifacts.update(spec.extra_artifacts(conn.properties))
    scaling = None
    if p.scaling:
        sc = p.scaling
        lo, hi = sc.min or 1, sc.max or sc.max_parallelism
        scaling = {
            "max_parallelism": sc.max_parallelism, "parallelism": sc.parallelism, "min": sc.min, "max": sc.max,
            "target_utilization": sc.target_utilization, "max_lag_ms": sc.max_lag_ms, "autoscale": sc.autoscale,
            "aligned_parallelisms": aligned_parallelisms(sc.max_parallelism, lo, hi)
            if sc.max_parallelism and hi else None,
            "models": {m.name: {"min": m.scaling.min, "max": m.scaling.max}
                       for m in p.models.values() if m.scaling},
        }
    runtime_fns = [cls for fn, cls in ((ASSERT_FN, ASSERT_CLASS), (EXPECT_FN, EXPECT_CLASS)) if f"{fn}(" in sql]
    return {
        "format_version": 2,  # 2: name-free logic hashes
        "compiler": f"cascade {__version__}",
        "pipeline": p.name,
        "environment": p.env,
        "owner": p.owner,
        "sql_sha256": hashlib.sha256(sql.encode()).hexdigest(),
        "flink_config": p.flink_config,
        "state_ttl_ms": p.state_ttl_ms,
        "scaling": scaling,
        "nodes": nodes,
        "sinks": sinks,
        "secrets": sorted(p.secrets),
        "secret_refs_in_options": sorted({v for opts in c.options.values() for v in opts.values()
                                          if SECRET_RE.match(v) or "${secret:" in v}),
        "artifacts": sorted(artifacts),
        "runtime_functions": runtime_fns,
        "functions": {f.name: {"language": f.language, "class": f.class_name, "jar": f.jar, "file": f.file,
                               "function": f.function, "returns": f.returns.text if f.returns else None,
                               "deterministic": f.deterministic} for f in p.functions.values()},
    }


def _unnamed_sql(c: Checked, name: str) -> str:
    """The model's SQL with each referenced source/model replaced by its input position."""
    import re
    sql = c.pipeline.models[name].sql
    a = c.analyses.get(name)
    if a is None:
        return sql
    inputs = c.pipeline.relations[name].inputs
    for r in sorted(a.refs, key=lambda r: -r.pos):
        if r.name not in inputs:
            continue
        m = re.compile(r"`?" + re.escape(r.name) + r"`?", re.IGNORECASE).match(sql, r.pos)
        if m:
            sql = sql[:m.start()] + f"_input{inputs.index(r.name)}" + sql[m.end():]
    return sql


def mermaid(c: Checked) -> str:
    p = c.pipeline
    lines = ["flowchart LR"]
    for s in p.sources.values():
        lines.append(f"  {s.name}[(\"{s.name}<br/><small>{p.relations[s.name].changelog}</small>\")]")
    for n in c.order:
        rel = p.relations[n]
        ops = ", ".join(sorted({o.kind for o in rel.stateful_ops})) or "stateless"
        lines.append(f"  {n}[\"{n}<br/><small>{ops} · {rel.changelog}</small>\"]")
        for i in rel.inputs:
            lines.append(f"  {i} --> {n}")
    for k in p.sinks.values():
        lines.append(f"  {k.name}[/\"{k.name}<br/><small>{k.mode}</small>\"/]")
        lines.append(f"  {k.from_} --> {k.name}")
    return "\n".join(lines) + "\n"
