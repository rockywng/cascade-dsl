"""User-defined functions.

Java: a ScalarFunction class, optionally in a project jar. Lowered to
  CREATE TEMPORARY SYSTEM FUNCTION f AS 'com.acme.F' LANGUAGE JAVA [USING JAR '...']

Python: a plain function in a module of the project; no PyFlink imports needed in user code, so it
is unit-testable with pytest. The compiler generates a shim module that wraps each function with
PyFlink's `udf(...)` and its declared result type:

  .cascade/python/cascade_udfs.py      churn_score = udf(scoring.churn_score, result_type="DOUBLE")
  .cascade/python/scoring.py           copy of the project's module

and lowers to SET 'python.files' = '<that dir>' + CREATE ... AS 'cascade_udfs.churn_score' LANGUAGE PYTHON.
`cascade deploy` ships the same directory in a ConfigMap.
"""
from __future__ import annotations

import ast
import os
import shutil

from . import __version__
from .ir import Pipeline

SHIM_MODULE = "cascade_udfs"
PYTHON_DIR = os.path.join(".cascade", "python")


PYRUNNER = "cascade_pyrunner.py"


def python_dir(p: Pipeline) -> str:
    return os.path.join(p.root_dir, PYTHON_DIR)


def python_functions(p: Pipeline) -> list:
    return [f for f in p.functions.values() if f.language == "python"]


def python_processes(p: Pipeline) -> list:
    return [m for m in p.models.values() if m.process and m.process.get("language") == "python"
            and m.copy_of is None]


def needs_python(p: Pipeline) -> bool:
    """PyFlink at runtime: Python UDFs, or Python process models (the job is driven by pyrunner.py)."""
    return bool(python_functions(p) or python_processes(p))


def plain_type(t) -> str:
    """A type as PyFlink's type-string parser reads it (no backquoted ROW field names)."""
    if t.name == "ROW":
        inner = ", ".join(f"{n} {plain_type(ft)}" for n, ft in t.params)
        return f"ROW<{inner}>" + ("" if t.nullable else " NOT NULL")
    if t.name in ("ARRAY", "MULTISET"):
        return f"{t.name}<{plain_type(t.params[0])}>" + ("" if t.nullable else " NOT NULL")
    if t.name == "MAP":
        return f"MAP<{plain_type(t.params[0])}, {plain_type(t.params[1])}>" + ("" if t.nullable else " NOT NULL")
    return t.text


AGG_ADAPTER = '''
class _Aggregate(_AggregateFunction):
    """A plain class (create_accumulator, accumulate, get_value; optionally retract and merge) as a PyFlink
    aggregate function. A list or tuple accumulator becomes a Row when the accumulator type is a ROW."""

    def __init__(self, cls, row_accumulator):
        self._impl = cls()
        self._row = row_accumulator

    def create_accumulator(self):
        acc = self._impl.create_accumulator()
        return _Row(*acc) if self._row and isinstance(acc, (list, tuple)) else acc

    def accumulate(self, accumulator, *args):
        self._impl.accumulate(accumulator, *args)

    def retract(self, accumulator, *args):
        if not hasattr(self._impl, "retract"):
            raise RuntimeError(f"{type(self._impl).__name__} has no retract(), so it can't aggregate updating input")
        self._impl.retract(accumulator, *args)

    def merge(self, accumulator, accumulators):
        if not hasattr(self._impl, "merge"):
            raise RuntimeError(f"{type(self._impl).__name__} has no merge()")
        self._impl.merge(accumulator, list(accumulators))

    def get_value(self, accumulator):
        return self._impl.get_value(accumulator)
'''


def shim(p: Pipeline) -> str:
    fns = python_functions(p)
    lines = [f"# Generated by cascade {__version__} for pipeline {p.name}. Do not edit.",
             "# Wraps the project's plain Python functions and classes as PyFlink functions.",
             "from pyflink.table.udf import udf, udaf, udtf"]
    if any(f.kind == "aggregate" for f in fns):
        lines += ["from pyflink.common import Row as _Row",
                  "from pyflink.table.udf import AggregateFunction as _AggregateFunction", AGG_ADAPTER]
    lines.append("")
    for f in fns:
        if f.kind == "aggregate":
            row_acc = f.accumulator is not None and f.accumulator.name == "ROW"
            lines.append(f"from {f.module} import {f.class_attr} as _{f.name}")
            lines.append(f"{f.name} = udaf(_Aggregate(_{f.name}, {row_acc!r}), result_type={plain_type(f.returns)!r}, "
                         f"accumulator_type={plain_type(f.accumulator)!r}, deterministic={f.deterministic!r}, "
                         "func_type='general')")
            continue
        lines.append(f"from {f.module} import {f.function} as _{f.name}")
        if f.kind == "table":
            lines.append(f"{f.name} = udtf(_{f.name}, result_types={plain_type(f.returns)!r}, "
                         f"deterministic={f.deterministic!r})")
        else:
            lines.append(f"{f.name} = udf(_{f.name}, result_type={f.returns.text!r}, "
                         f"deterministic={f.deterministic!r})")
    return "\n".join(lines) + "\n"


def write_python_dir(p: Pipeline) -> str | None:
    """Materialize the shim and copies of the user modules. Returns the directory, or None."""
    fns = python_functions(p)
    if not fns:
        return None
    d = python_dir(p)
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, ".gitignore"), "w") as f:
        f.write("*\n")
    for f in fns:
        shutil.copy(os.path.join(p.root_dir, f.file), os.path.join(d, os.path.basename(f.file)))
    with open(os.path.join(d, f"{SHIM_MODULE}.py"), "w") as f:
        f.write(shim(p))
    return d


def python_files(p: Pipeline) -> dict[str, str]:
    """File name -> content of everything the Python workers import (for the deploy ConfigMap)."""
    out = {f"{SHIM_MODULE}.py": shim(p)} if python_functions(p) else {}
    for f in python_functions(p):
        with open(os.path.join(p.root_dir, f.file)) as fh:
            out[os.path.basename(f.file)] = fh.read()
    if python_processes(p):
        with open(os.path.join(os.path.dirname(__file__), "pyrunner.py")) as fh:
            out[PYRUNNER] = fh.read()
        for m in python_processes(p):
            with open(os.path.join(p.root_dir, m.process["file"])) as fh:
                out[os.path.basename(m.process["file"])] = fh.read()
    return out


def check_python_module(path: str, function: str, kind: str = "function") -> str | None:
    """Static check (no import, no execution): the module parses and defines `function` (or, for
    aggregate functions, a class) at top level."""
    try:
        with open(path) as f:
            tree = ast.parse(f.read(), filename=path)
    except SyntaxError as e:
        return f"syntax error at line {e.lineno}: {e.msg}"
    for node in tree.body:
        if kind == "class" and isinstance(node, ast.ClassDef) and node.name == function:
            missing = {"create_accumulator", "accumulate", "get_value"} - {
                b.name for b in node.body if isinstance(b, ast.FunctionDef)}
            return f"class '{function}' lacks {', '.join(sorted(missing))}" if missing else None
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name == function:
            return None
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == function for t in node.targets):
            return None
    return f"does not define a top-level {kind} '{function}'"
