"""User-defined functions.

Java: a ScalarFunction class, optionally in a project jar. Lowered to
  CREATE TEMPORARY SYSTEM FUNCTION f AS 'com.acme.F' LANGUAGE JAVA [USING JAR '...']

Python: a plain function in a module of the project; no PyFlink imports needed in user code, so it
is unit-testable with pytest. The compiler generates a shim module that wraps each function with
PyFlink's `udf(...)` and its declared result type:

  .cascade/python/cascade_udfs.py      churn_score = udf(scoring.churn_score, result_type="DOUBLE")
  .cascade/python/scoring.py           copy of the project's module

and lowers to SET 'python.files' = '<that dir>' + CREATE ... AS 'cascade_udfs.churn_score' LANGUAGE PYTHON.
`cascade deploy` ships the same directory in a ConfigMap.
"""
from __future__ import annotations

import ast
import os
import shutil

from . import __version__
from .ir import Pipeline

SHIM_MODULE = "cascade_udfs"
PYTHON_DIR = os.path.join(".cascade", "python")


def python_dir(p: Pipeline) -> str:
    return os.path.join(p.root_dir, PYTHON_DIR)


def python_functions(p: Pipeline) -> list:
    return [f for f in p.functions.values() if f.language == "python"]


def shim(p: Pipeline) -> str:
    lines = [f"# Generated by cascade {__version__} for pipeline {p.name}. Do not edit.",
             "# Wraps the project's plain Python functions as PyFlink scalar functions.",
             "from pyflink.table.udf import udf", ""]
    for f in python_functions(p):
        lines.append(f"from {f.module} import {f.function} as _{f.name}")
        lines.append(f"{f.name} = udf(_{f.name}, result_type={f.returns.text!r}, "
                     f"deterministic={f.deterministic!r})")
    return "\n".join(lines) + "\n"


def write_python_dir(p: Pipeline) -> str | None:
    """Materialize the shim and copies of the user modules. Returns the directory, or None."""
    fns = python_functions(p)
    if not fns:
        return None
    d = python_dir(p)
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, ".gitignore"), "w") as f:
        f.write("*\n")
    for f in fns:
        shutil.copy(os.path.join(p.root_dir, f.file), os.path.join(d, os.path.basename(f.file)))
    with open(os.path.join(d, f"{SHIM_MODULE}.py"), "w") as f:
        f.write(shim(p))
    return d


def python_files(p: Pipeline) -> dict[str, str]:
    """File name -> content of everything the Python workers import (for the deploy ConfigMap)."""
    out = {f"{SHIM_MODULE}.py": shim(p)}
    for f in python_functions(p):
        with open(os.path.join(p.root_dir, f.file)) as fh:
            out[os.path.basename(f.file)] = fh.read()
    return out


def check_python_module(path: str, function: str) -> str | None:
    """Static check (no import, no execution): the module parses and defines `function` at top level."""
    try:
        with open(path) as f:
            tree = ast.parse(f.read(), filename=path)
    except SyntaxError as e:
        return f"syntax error at line {e.lineno}: {e.msg}"
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name == function:
            return None
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == function for t in node.targets):
            return None
    return f"does not define a top-level function '{function}'"
