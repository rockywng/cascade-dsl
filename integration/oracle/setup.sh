#!/bin/bash
# Oracle XE 21c for Flink CDC (LogMiner): archivelog mode, supplemental logging, a common CDC user, and
# a table in the pluggable database XEPDB1. Run inside the container (integration/connectors.py).
set -e
sqlplus -s / as sysdba <<'SQL'
WHENEVER SQLERROR EXIT FAILURE
ALTER SYSTEM SET db_recovery_file_dest_size = 10G;
SHUTDOWN IMMEDIATE;
STARTUP MOUNT;
ALTER DATABASE ARCHIVELOG;
ALTER DATABASE OPEN;
ALTER PLUGGABLE DATABASE ALL OPEN;
ALTER DATABASE ADD SUPPLEMENTAL LOG DATA;
CREATE TABLESPACE logminer_tbs DATAFILE '/opt/oracle/oradata/XE/logminer_tbs.dbf' SIZE 25M REUSE AUTOEXTEND ON MAXSIZE UNLIMITED;
ALTER SESSION SET CONTAINER = XEPDB1;
CREATE TABLESPACE logminer_tbs DATAFILE '/opt/oracle/oradata/XE/XEPDB1/logminer_tbs.dbf' SIZE 25M REUSE AUTOEXTEND ON MAXSIZE UNLIMITED;
CREATE USER app IDENTIFIED BY apppw QUOTA UNLIMITED ON users;
GRANT CREATE SESSION, CREATE TABLE TO app;
CREATE TABLE app.items (id NUMBER(10) PRIMARY KEY, name VARCHAR2(20), qty NUMBER(10));
ALTER TABLE app.items ADD SUPPLEMENTAL LOG DATA (ALL) COLUMNS;
INSERT INTO app.items VALUES (1, 'a', 5);
INSERT INTO app.items VALUES (2, 'b', 7);
INSERT INTO app.items VALUES (3, 'c', 9);
COMMIT;
ALTER SESSION SET CONTAINER = CDB$ROOT;
CREATE USER c##flinkuser IDENTIFIED BY flinkpw DEFAULT TABLESPACE logminer_tbs QUOTA UNLIMITED ON logminer_tbs CONTAINER = ALL;
GRANT CREATE SESSION, SET CONTAINER, SELECT ON V_$DATABASE, FLASHBACK ANY TABLE, SELECT ANY TABLE,
  SELECT_CATALOG_ROLE, EXECUTE_CATALOG_ROLE, SELECT ANY TRANSACTION, LOGMINING, CREATE TABLE, LOCK ANY TABLE,
  CREATE SEQUENCE, EXECUTE ON DBMS_LOGMNR, EXECUTE ON DBMS_LOGMNR_D, SELECT ON V_$LOG, SELECT ON V_$LOG_HISTORY,
  SELECT ON V_$LOGMNR_LOGS, SELECT ON V_$LOGMNR_CONTENTS, SELECT ON V_$LOGMNR_PARAMETERS, SELECT ON V_$LOGFILE,
  SELECT ON V_$ARCHIVED_LOG, SELECT ON V_$ARCHIVE_DEST_STATUS, SELECT ANY DICTIONARY, ANALYZE ANY
  TO c##flinkuser CONTAINER = ALL;
EXIT
SQL
echo "oracle ready for cdc"
